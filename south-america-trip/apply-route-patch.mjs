import fs from 'node:fs';
const tripPath='public/data/trip-v2.json';
const patch=JSON.parse(fs.readFileSync('route-patch.json','utf8'));
const trip=JSON.parse(fs.readFileSync(tripPath,'utf8'));
const merge=(a,b)=>{if(!b||typeof b!=='object'||Array.isArray(b))return b;const out={...(a||{})};for(const [k,v] of Object.entries(b))out[k]=(v&&typeof v==='object'&&!Array.isArray(v))?merge(out[k],v):v;return out};
const patchBy=(arr,key,items)=>{const out=[...arr];for(const [id,p] of Object.entries(items)){const i=out.findIndex(x=>x[key]===id);if(i>=0)out[i]=merge(out[i],p);else out.push(p)}return out};
trip.version=patch.version;trip.routeSummary=patch.routeSummary;trip.criticalAlert=patch.criticalAlert;
trip.days=patchBy(trip.days,'date',patch.days);
trip.stays=patchBy(trip.stays,'id',patch.stays).sort((a,b)=>a.checkIn.localeCompare(b.checkIn)||a.id.localeCompare(b.id));
trip.transport=patchBy(trip.transport,'id',patch.transport);
trip.activities=patchBy(trip.activities,'id',patch.activities);
trip.bookings=patchBy(trip.bookings,'id',patch.bookings);
trip.rules=trip.rules.map(r=>r.title===patch.rule.title?patch.rule:r);
trip.places=trip.places.filter(p=>!patch.removePlaces.includes(p.id));
fs.writeFileSync(tripPath,JSON.stringify(trip)+'\n');
